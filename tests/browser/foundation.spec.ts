import { readFileSync } from 'node:fs'
import { join } from 'node:path'
import { expect, test } from '@playwright/test'

const origin = 'http://127.0.0.1:3187'
const password = 'a-long-browser-test-password'

test('setup, protected overview, durable system check, backup and sign-in', async ({ page, browser }, testInfo) => {
  expect((await page.request.get('/api/health/ready')).status()).toBe(200)
  expect((await page.request.get('/api/status')).status()).toBe(401)
  expect((await page.request.post('/api/auth/setup', { data: {} })).status()).toBe(403)
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Make yourself at home.' })).toBeVisible()
  await page.getByLabel('Setup token').fill(readFileSync(join(testInfo.config.metadata.dataDir, 'setup.token'), 'utf8').trim())
  await page.getByLabel('Username', { exact: true }).fill('admin')
  await page.getByLabel('Password', { exact: false }).fill(password)
  await page.getByRole('button', { name: 'Create account' }).click()
  await expect(page.getByRole('heading', { name: 'Overview.' })).toBeVisible()
  const sessionCookie = (await page.context().cookies()).find(c => c.name === 'chur_session')
  expect(sessionCookie?.httpOnly).toBe(true)
  expect(sessionCookie?.sameSite).toBe('Strict')
  const status = await (await page.request.get('/api/status')).json()
  expect(status.mode).toBe('dry-run')
  expect(status.automationEnabled).toBe(false)
  expect(status.connectionsConfigured).toBe(0)
  expect(JSON.stringify(status)).not.toMatch(/password|master.key|setup.token|dataDir/)
  expect((await page.request.post('/api/jobs', { headers: { Origin: 'https://untrusted.invalid' }, data: { kind: 'system.check', requestId: crypto.randomUUID() } })).status()).toBe(403)
  const csrf = (await (await page.request.get('/api/auth/status')).json()).csrfToken
  const csrfCookie = (await page.context().cookies()).find(c => c.name === 'chur_csrf')
  expect(csrfCookie?.httpOnly).toBe(true)
  expect((await page.request.post('/api/jobs', { headers: { 'X-CSRF-Token': 'invalid' }, data: {} })).status()).toBe(403)
  expect((await page.request.post('/api/jobs', { headers: { 'X-CSRF-Token': csrf, 'Sec-Fetch-Site': 'cross-site' }, data: {} })).status()).toBe(403)
  // Valid tokens work without an Origin header or any public URL configuration.
  expect((await page.request.post('/api/jobs', { headers: { 'X-CSRF-Token': csrf }, data: { kind: 'download', requestId: crypto.randomUUID() } })).status()).toBe(400)
  await page.getByRole('button', { name: 'Run system check' }).click()
  await expect(page.getByTestId('job-status').first()).toHaveText('succeeded', { timeout: 10_000 })
  await page.reload()
  await expect(page.getByTestId('job-status').first()).toHaveText('succeeded')
  await page.getByRole('button', { name: 'Create backup' }).click()
  await expect(page.getByRole('status')).toHaveText('Backup saved on this server.')
  await page.screenshot({ path: 'test-results/overview.png', fullPage: true })
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: 'Overview.' })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.screenshot({ path: 'test-results/overview-mobile.png', fullPage: true })
  await page.getByRole('button', { name: 'Sign out' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  expect((await page.request.get('/api/status')).status()).toBe(401)
  expect((await page.request.post('/api/auth/login', { data: { username: 'admin', password } })).status()).toBe(403)
  expect((await page.request.post('/api/auth/logout', { headers: { 'X-CSRF-Token': csrf } })).status()).toBe(403)
  await page.getByLabel('Password', { exact: false }).fill('wrong-password')
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Invalid username or password.')
  await page.getByLabel('Password', { exact: false }).fill(password)
  await page.getByRole('button', { name: 'Sign in', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Overview.' })).toBeVisible()
  const separate = await browser.newContext()
  const other = await separate.newPage()
  await other.goto(origin)
  await expect(other.getByRole('heading', { name: 'Welcome back.' })).toBeVisible()
  await separate.close()
})
